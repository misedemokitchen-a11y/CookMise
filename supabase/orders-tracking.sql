-- ── One row per grocery item (clean, exportable; replaces reading orders.items) ──
create table if not exists order_items (
  id            bigint generated by default as identity primary key,
  order_id      uuid not null references orders(id) on delete cascade,
  position      integer not null default 0,
  ingredient    text not null,
  qty           text,
  product_name  text,
  product_brand text,
  price         numeric,
  image         text,
  created_at    timestamptz default now()
);
create index if not exists order_items_order_id_idx on order_items(order_id);

alter table order_items enable row level security;
drop policy if exists "Users read own order items"   on order_items;
drop policy if exists "Users insert own order items" on order_items;
create policy "Users read own order items" on order_items for select
  using (exists (select 1 from orders o where o.id = order_id and o.user_id = auth.uid()));
create policy "Users insert own order items" on order_items for insert
  with check (exists (select 1 from orders o where o.id = order_id and o.user_id = auth.uid()));

-- Backfill items from orders already placed (skips orders that have rows).
insert into order_items (order_id, position, ingredient, qty, product_name, product_brand, price, image)
select o.id, (e.ord - 1)::int, e.item->>'ingredient', e.item->>'qty',
       e.item->'product'->>'name', e.item->'product'->>'brand',
       nullif(e.item->'product'->>'price','')::numeric, e.item->'product'->>'image'
from orders o, jsonb_array_elements(o.items) with ordinality as e(item, ord)
where o.items is not null and jsonb_typeof(o.items) = 'array'
  and not exists (select 1 from order_items oi where oi.order_id = o.id);
